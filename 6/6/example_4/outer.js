// определение функции-выражения
let fnSayHi = () => {
	// вывод сообщения в диалог
	alert ("Я внешний скрипт!");
	
	// вывод сообщения в консоль
	console.log("Я внешний скрипт!");

	// вывод сообщения в документ
	document.body.insertAdjacentHTML("beforeend", "<h2>Я внешний скрипт!</h2>");
}

// вызов функции
fnSayHi();